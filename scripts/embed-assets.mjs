import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const dist = "apps/web/dist";
const out = "apps/api/src/assets.generated.ts";
const binary = new Set([".woff", ".woff2", ".png", ".webp", ".ico", ".gif"]);
const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".png": "image/png",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
};

function files(dir) {
  const found = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) found.push(...files(path));
    else if (extname(name) !== ".map") found.push(path);
  }
  return found;
}

const assets = {};
for (const path of files(dist)) {
  const ext = extname(path);
  const urlPath = `/${relative(dist, path).split("\\").join("/")}`;
  const contentType = types[ext] ?? "application/octet-stream";
  if (binary.has(ext)) {
    assets[urlPath] = { body: readFileSync(path).toString("base64"), contentType, base64: true };
  } else {
    assets[urlPath] = { body: readFileSync(path, "utf8"), contentType, base64: false };
  }
}

const source = `// Generated by scripts/embed-assets.mjs. Do not edit.
export type EmbeddedAsset = { body: string; contentType: string; base64: boolean };
export const ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(assets)};
`;
writeFileSync(out, source);
console.log(`Embedded ${Object.keys(assets).length} files into ${out}`);
