import type { AcceptedSeed, NameOneSeed } from "./name-one.ts";
import { moreFun } from "./seven.ts";

/**
 * SAMPLE fun week: seven daily Classic days and three Ballpark+ themed packs, all "name one" questions.
 * The voice is playful on purpose: a cheeky prompt, then a reveal with a fact worth repeating.
 * Priors are rough editorial guesses at how often players give each answer. Lists are pending editorial
 * verification, like the rest of the sample.
 */

function a(canonical: string, prior: number, aliases: string[] = []): AcceptedSeed {
  return { canonical, prior, aliases };
}

const CC = "CC BY-SA 4.0";
const wiki = (page: string) => `https://en.wikipedia.org/wiki/${page}`;

function q(
  id: string,
  prompt: string,
  accepted: AcceptedSeed[],
  context: string,
  page: string,
  topic: string,
  difficulty: 1 | 2 | 3,
  entitySet: NameOneSeed["entitySet"] = null,
): NameOneSeed {
  return {
    id,
    prompt,
    entitySet,
    accepted,
    context,
    sourceName: `Wikipedia: ${decodeURIComponent(page).replaceAll("_", " ")}`,
    sourceUrl: wiki(page),
    license: CC,
    topic,
    difficulty,
  };
}

