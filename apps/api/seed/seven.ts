import type { AcceptedSeed, NameOneSeed } from "./name-one.ts";

/**
 * SAMPLE: the two extra questions each Classic day gained when Classic went from five questions to seven.
 * Same voice as the fun week: a cheeky prompt, then a reveal worth repeating. Priors are rough editorial
 * guesses at how often players give each answer, and the lists are pending editorial verification.
 */

function a(canonical: string, prior: number, aliases: string[] = []): AcceptedSeed {
  return { canonical, prior, aliases };
}

const CC = "CC BY-SA 4.0";

function q(
  id: string,
  prompt: string,
  accepted: AcceptedSeed[],
  context: string,
  page: string,
  topic: string,
  difficulty: 1 | 2 | 3,
  entitySet: NameOneSeed["entitySet"] = null,
): NameOneSeed {
  return {
    id,
    prompt,
    entitySet,
    accepted,
    context,
    sourceName: `Wikipedia: ${decodeURIComponent(page).replaceAll("_", " ")}`,
    sourceUrl: `https://en.wikipedia.org/wiki/${page}`,
    license: CC,
    topic,
    difficulty,
  };
}

