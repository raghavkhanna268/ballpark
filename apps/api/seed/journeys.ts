import type { AcceptedSeed, NameOneSeed } from "./name-one.ts";

/**
 * SAMPLE pack journeys: chapters 2 and 3 of each Ballpark+ pack. Chapter 1 is the pack's original five questions
 * in fun.ts. Same voice and rules as the fun week: playful prompts, facts that do not change often, priors as
 * rough editorial guesses, and lists pending editorial verification.
 */

function a(canonical: string, prior: number, aliases: string[] = []): AcceptedSeed {
  return { canonical, prior, aliases };
}

const CC = "CC BY-SA 4.0";

function q(
  id: string,
  prompt: string,
  accepted: AcceptedSeed[],
  context: string,
  page: string,
  topic: string,
  difficulty: 1 | 2 | 3,
): NameOneSeed {
  return {
    id,
    prompt,
    entitySet: null,
    accepted,
    context,
    sourceName: `Wikipedia: ${decodeURIComponent(page).replaceAll("_", " ")}`,
    sourceUrl: `https://en.wikipedia.org/wiki/${page}`,
    license: CC,
    topic,
    difficulty,
  };
}

